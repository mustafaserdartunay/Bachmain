export function formatTry(value: number) {
  return `₺${Number(value || 0).toLocaleString('tr-TR', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  })}`
}

export function moduleUnitPrice(
  mod: { monthlyPrice: number; yearlyPrice: number },
  period: 'month' | 'year',
) {
  return period === 'year' ? Number(mod.yearlyPrice) || 0 : Number(mod.monthlyPrice) || 0
}

export function modulePriceSuffix(period: 'month' | 'year') {
  return period === 'year' ? '/ yıl' : '/ ay'
}
