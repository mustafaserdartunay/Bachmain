export function t(key, lang = 'tr') {
  return UI[lang]?.[key] || UI.tr[key] || key
}

export function translateLive(text, targetLang = 'en') {
  if (!text || targetLang === 'tr') return text
  return String(text)
    .split(/(\s+)/)
    .map((token) => {
      const normalized = token.toLocaleLowerCase('tr-TR').replace(/[^a-zçğıöşü0-9]/gi, '')
      const hit = GLOSSARY_TR[normalized]
      if (hit?.[targetLang]) {
        const preserved = token === token.toUpperCase() ? hit[targetLang].toUpperCase() : hit[targetLang]
        return preserved
      }
      return token
    })
    .join('')
}
